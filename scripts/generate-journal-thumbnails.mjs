#!/usr/bin/env node
import { createHash } from 'node:crypto';
import { promises as fs } from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import sharp from 'sharp';

const ROOT = process.cwd();
const JOURNAL_DIR = path.join(ROOT, 'src/content/journal');
const PUBLIC_DIR = path.join(ROOT, 'public');
const OUTPUT_DIR = path.join(PUBLIC_DIR, 'images/journal/thumbnails');
const DATA_FILE = path.join(ROOT, 'src/data/journalThumbnails.ts');
const WIDTHS = [800];
const QUALITY = 75;
const FORCE = process.argv.includes('--force');

function hash(input) {
  return createHash('sha1').update(input).digest('hex').slice(0, 8);
}

function slugify(input) {
  return input
    .toLowerCase()
    .replace(/\.[a-z0-9]+$/i, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '') || 'journal-image';
}

async function listMarkdownFiles(dir) {
  const entries = await fs.readdir(dir, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    const entryPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...await listMarkdownFiles(entryPath));
    } else if (entry.isFile() && entry.name.endsWith('.md')) {
      files.push(entryPath);
    }
  }

  return files;
}

function extractFrontmatterImage(markdown) {
  const match = markdown.match(/^---\n([\s\S]*?)\n---/);
  if (!match) return undefined;

  const imageMatch = match[1].match(/^image:\s*["']?([^"'\n]+)["']?\s*$/m);
  return imageMatch?.[1]?.trim();
}

function getOutputPath(src, width) {
  const parsed = path.posix.parse(src);
  const name = `${slugify(parsed.base)}-${hash(src)}-${width}.webp`;
  return {
    file: path.join(OUTPUT_DIR, name),
    publicPath: `/images/journal/thumbnails/${name}`,
  };
}

async function isUpToDate(inputFile, outputFile) {
  if (FORCE) return false;

  try {
    const [inputStat, outputStat] = await Promise.all([
      fs.stat(inputFile),
      fs.stat(outputFile),
    ]);
    return outputStat.mtimeMs >= inputStat.mtimeMs;
  } catch {
    return false;
  }
}

async function generateThumbnail(inputFile, outputFile, width) {
  if (await isUpToDate(inputFile, outputFile)) return { skipped: true, bytes: 0 };

  await sharp(inputFile)
    .rotate()
    .resize(width, width, {
      fit: 'cover',
      position: 'centre',
      withoutEnlargement: false,
    })
    .webp({ quality: QUALITY, effort: 5 })
    .toFile(outputFile);

  const stat = await fs.stat(outputFile);
  return { skipped: false, bytes: stat.size };
}

function formatBytes(bytes) {
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(1)} KB`;
  return `${(bytes / 1024 / 1024).toFixed(1)} MB`;
}

function renderDataFile(manifest) {
  return `// Auto-generated by scripts/generate-journal-thumbnails.mjs. Do not edit manually.\n\nexport type JournalThumbnail = {\n  src: string;\n  srcset: string;\n  width: number;\n  height: number;\n};\n\nexport const journalThumbnails = ${JSON.stringify(manifest, null, 2)} as const satisfies Record<string, JournalThumbnail>;\n\nexport function getJournalThumbnail(src?: string): JournalThumbnail | undefined {\n  if (!src) return undefined;\n  return journalThumbnails[src as keyof typeof journalThumbnails];\n}\n\nexport function getJournalThumbnailSrc(src?: string): string | undefined {\n  return getJournalThumbnail(src)?.src ?? src;\n}\n`;
}

async function main() {
  await fs.mkdir(OUTPUT_DIR, { recursive: true });

  const markdownFiles = await listMarkdownFiles(JOURNAL_DIR);
  const imageSources = new Set();

  for (const file of markdownFiles) {
    const markdown = await fs.readFile(file, 'utf8');
    const src = extractFrontmatterImage(markdown);
    if (src?.startsWith('/images/journal/')) imageSources.add(src);
  }

  const manifest = {};
  let originalBytes = 0;
  let generatedBytes = 0;
  let generatedCount = 0;
  let skippedCount = 0;
  let removedCount = 0;
  const expectedFiles = new Set();
  const missing = [];

  for (const src of [...imageSources].sort()) {
    const inputFile = path.join(PUBLIC_DIR, src.slice(1));

    try {
      originalBytes += (await fs.stat(inputFile)).size;
    } catch {
      missing.push(src);
      continue;
    }

    const variants = [];
    for (const width of WIDTHS) {
      const output = getOutputPath(src, width);
      expectedFiles.add(output.file);
      const result = await generateThumbnail(inputFile, output.file, width);
      if (result.skipped) skippedCount += 1;
      else generatedCount += 1;
      generatedBytes += (await fs.stat(output.file)).size;
      variants.push({ width, publicPath: output.publicPath });
    }

    const largest = variants.at(-1);
    manifest[src] = {
      src: largest.publicPath,
      srcset: variants.map((variant) => `${variant.publicPath} ${variant.width}w`).join(', '),
      width: largest.width,
      height: largest.width,
    };
  }

  for (const entry of await fs.readdir(OUTPUT_DIR, { withFileTypes: true })) {
    if (!entry.isFile() || !entry.name.endsWith('.webp')) continue;
    const file = path.join(OUTPUT_DIR, entry.name);
    if (!expectedFiles.has(file)) {
      await fs.rm(file);
      removedCount += 1;
    }
  }

  await fs.writeFile(DATA_FILE, renderDataFile(manifest));

  console.log(`Journal thumbnail sources: ${imageSources.size}`);
  console.log(`Generated variants: ${generatedCount}; skipped up-to-date: ${skippedCount}; removed stale: ${removedCount}`);
  console.log(`Original frontmatter image weight: ${formatBytes(originalBytes)}`);
  console.log(`Generated thumbnail weight: ${formatBytes(generatedBytes)}`);
  console.log(`Manifest: ${path.relative(ROOT, DATA_FILE)}`);

  if (missing.length) {
    console.warn(`Missing source images (${missing.length}):`);
    for (const src of missing) console.warn(`- ${src}`);
    process.exitCode = 1;
  }
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
